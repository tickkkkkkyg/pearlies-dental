export function whatsAppLink(message: string = whatsappConfig.message): string | null {
  if (!whatsappConfig.enabled) return null;
  const phone = whatsappConfig.phone.replace(/[^\d]/g, "");
  return `https://wa.me/${phone}?text=${encodeURIComponent(message)}`;
}
